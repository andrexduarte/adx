import { writeFile } from 'node:fs/promises';

// Public profile data only; no token or runtime request from the visitor's browser.
const profile = 'andrexduarte';
const years = [2026, 2025];
const snapshots = await Promise.all(years.map(async year => {
  const source = `https://github.com/users/${profile}/contributions?from=${year}-01-01&to=${year}-12-31`;
  const response = await fetch(source);
  if (!response.ok) throw new Error(`GitHub ${year}: HTTP ${response.status}`);
  const html = await response.text();
  const attributes = tag => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(match => [match[1], match[2]]));
  const tips = new Map([...html.matchAll(/<tool-tip\b([^>]*)>([^<]*)<\/tool-tip>/g)].map(match => [attributes(match[1]).for, match[2].trim()]));
  const days = [...html.matchAll(/<td\b[^>]*data-date="[^"]+"[^>]*>/g)].map(([tag]) => {
    const attr = attributes(tag);
    const tip = tips.get(attr.id)?.match(/^(No|[\d,]+) contributions? on /);
    if (!tip) throw new Error(`Missing daily count: ${attr['data-date']}`);
    return [attr['data-date'], tip[1] === 'No' ? 0 : Number(tip[1].replaceAll(',', '')), Number(attr['data-level'])];
  }).filter(day => day[0].startsWith(`${year}-`)).sort((a, b) => a[0].localeCompare(b[0]));
  const total = Number(html.match(/id="js-contribution-activity-description"[^>]*>\s*([\d,]+)\s+contributions/)?.[1].replaceAll(',', ''));
  const expectedDays = (Date.UTC(year + 1, 0, 1) - Date.UTC(year, 0, 1)) / 86400000;
  if (days.length !== expectedDays || days.some(([date, count, level], index) =>
    date !== new Date(Date.UTC(year, 0, 1 + index)).toISOString().slice(0, 10) ||
    !Number.isInteger(count) || count < 0 || !Number.isInteger(level) || level < 0 || level > 4
  ) || days.reduce((sum, day) => sum + day[1], 0) !== total) {
    throw new Error(`Incomplete or inconsistent GitHub calendar for ${year}; snapshot was not replaced.`);
  }
  return { year, total, source, days };
}));
const snapshot = { profileUrl: `https://github.com/${profile}`, retrievedAt: new Date().toISOString().slice(0, 10), years: snapshots };
const output = `// Generated by scripts/sync-github-activity.mjs. Counts and intensity levels come from GitHub.\nimport type { ActivitySnapshot } from './activity-calendar';\nexport const GITHUB_ACTIVITY: ActivitySnapshot = ${JSON.stringify(snapshot, null, 2)};\n`;
await writeFile(new URL('../src/app/features/home/arena-story/github-activity-data.ts', import.meta.url), output);
console.log(snapshots.map(({ year, total, days }) => `${year}: ${total} contributions, ${days.length} verified days`).join('\n'));
